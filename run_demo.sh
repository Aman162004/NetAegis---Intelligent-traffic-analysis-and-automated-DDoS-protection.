#!/usr/bin/env bash

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    printf 'Run this helper in the current terminal with: source ./run_demo.sh\n' >&2
    exit 2
fi

DEMO_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)" || return 1

if ! command -v ipset >/dev/null 2>&1; then
    printf 'Error: ipset is not installed or is not on PATH.\n' >&2
    return 1
fi

if [[ ! -x "$DEMO_DIR/venv/bin/python" ]]; then
    printf 'Error: project venv is missing. Create it with: python3 -m venv "%s/venv"\n' "$DEMO_DIR" >&2
    return 1
fi

if ! source "$DEMO_DIR/venv/bin/activate"; then
    printf 'Error: could not activate the project virtual environment.\n' >&2
    return 1
fi

if ! python -c 'import fastapi, requests, scapy, uvicorn' >/dev/null 2>&1; then
    printf 'Error: project dependencies are missing from venv. Install with: python -m pip install -r "%s/requirements.txt"\n' "$DEMO_DIR" >&2
    return 1
fi

printf 'Project venv active: %s\n' "$VIRTUAL_ENV"
printf 'ipset found: %s\n' "$(command -v ipset)"
printf '\nUse these three terminals for a local-only, non-attack demonstration.\n'
printf 'Loopback, private, and documentation IPs are deliberately excluded from kernel blocks.\n'
printf 'Terminal 1 starts the API/dashboard bound to loopback only:\n'
printf 'cd %q && source venv/bin/activate && sudo -E "$VIRTUAL_ENV/bin/python" -m uvicorn mitigation.firewall:app --host 127.0.0.1 --port 5000\n' "$DEMO_DIR"
printf '\nTerminal 2 starts the passive packet sniffer (Ctrl-C to stop):\n'
printf 'cd %q && source venv/bin/activate && sudo -E "$VIRTUAL_ENV/bin/python" detection/sniffer.py\n' "$DEMO_DIR"
printf '\nTerminal 3 fetches the report and tails the audit log:\n'
printf 'cd %q && source venv/bin/activate && curl --fail-with-body --silent --show-error http://127.0.0.1:5000/api/cert-in-report | python -m json.tool && tail -n 10 -F config/audit.log\n' "$DEMO_DIR"
printf 'Open the live WebSocket dashboard in a browser: http://127.0.0.1:5000/\n'
printf '\nNo alert is generated by this helper. Loopback-only tests cannot safely demonstrate a real kernel block with the existing safeguards.\n'
